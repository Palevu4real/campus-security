import PDFDocument from 'pdfkit';
import { prisma } from '../config/prisma.js';

export async function generateIncidentReport({ from, to, req }) {
  const dateFilter = {};
  if (from) dateFilter.gte = new Date(from);
  if (to) dateFilter.lte = new Date(to);
  const dateWhere = Object.keys(dateFilter).length ? { createdAt: dateFilter } : {};

  const [alerts, tamperLogs, lockedUsers, activitySummary] = await Promise.all([
    prisma.alert.findMany({
      where: dateWhere,
      orderBy: { createdAt: 'desc' },
      take: 100,
      include: { targetUser: { select: { email: true, fullName: true } } },
    }),
    prisma.activityLog.findMany({
      where: { ...dateWhere, action: { in: ['TAMPER_ATTEMPT', 'DUPLICATE_RESULT_UPLOAD_ATTEMPT', 'UNAUTHORIZED_RESULT_UPLOAD_ATTEMPT'] } },
      orderBy: { createdAt: 'desc' },
      take: 50,
      include: { user: { select: { email: true } } },
    }),
    prisma.user.findMany({
      where: { isLocked: true },
      select: { email: true, fullName: true, role: true, failedAttempts: true, lockedReason: true, lockedAt: true },
    }),
    prisma.activityLog.groupBy({
      by: ['severity'],
      where: dateWhere,
      _count: { severity: true },
    }),
  ]);

  const doc = new PDFDocument({ size: 'A4', margin: 50 });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const done = new Promise((resolve) => doc.on('end', () => resolve(Buffer.concat(chunks))));

  const COLORS = {
    primary: '#4f46e5',
    critical: '#dc2626',
    warning: '#f59e0b',
    info: '#3b82f6',
    muted: '#6b7280',
    light: '#f3f4f6',
  };

  const pageWidth = doc.page.width - 100;

  doc.rect(0, 0, doc.page.width, 90).fill(COLORS.primary);
  doc.fillColor('white').fontSize(22).font('Helvetica-Bold').text('Campus Security System', 50, 30);
  doc.fontSize(11).font('Helvetica').text('Security Incident Report', 50, 60);

  doc.moveDown(3);

  const fromDate = from ? new Date(from).toLocaleDateString() : 'All time';
  const toDate = to ? new Date(to).toLocaleDateString() : 'Now';
  doc.fillColor(COLORS.muted).fontSize(10);
  doc.text(`Report generated: ${new Date().toLocaleString()}`, 50);
  doc.text(`Date range: ${fromDate} to ${toDate}`, 50);
  doc.text(`Generated by: Security Admin`, 50);

  doc.moveDown(1.5);

  doc.fillColor('black').fontSize(16).font('Helvetica-Bold').text('Executive Summary');
  doc.moveDown(0.5);

  const summaryData = [
    ['Total Alerts', alerts.length],
    ['Tamper Attempts', tamperLogs.length],
    ['Locked Accounts', lockedUsers.length],
    ['Critical Activity', activitySummary.find((a) => a.severity === 'CRITICAL')?._count.severity || 0],
  ];

  const boxWidth = (pageWidth - 30) / 2;
  let y = doc.y;
  summaryData.forEach((item, i) => {
    const x = i % 2 === 0 ? 50 : 50 + boxWidth + 30;
    const row = Math.floor(i / 2);
    const boxY = y + row * 55;

    doc.rect(x, boxY, boxWidth, 45).fillAndStroke(COLORS.light, '#e5e7eb');
    doc.fillColor(COLORS.muted).fontSize(9).font('Helvetica').text(item[0].toUpperCase(), x + 12, boxY + 10);
    doc.fillColor('black').fontSize(18).font('Helvetica-Bold').text(String(item[1]), x + 12, boxY + 22);
  });

  doc.moveDown(4);

  doc.addPage();
  doc.fillColor('black').fontSize(16).font('Helvetica-Bold').text('Security Alerts');
  doc.moveDown(0.5);
  doc.fillColor(COLORS.muted).fontSize(9).font('Helvetica').text(`Showing ${alerts.length} alerts (most recent first)`);
  doc.moveDown(0.8);

  if (alerts.length === 0) {
    doc.fillColor(COLORS.muted).fontSize(11).text('No alerts in this date range.');
  } else {
    alerts.slice(0, 30).forEach((a) => {
      if (doc.y > doc.page.height - 100) doc.addPage();
      const sevColor = COLORS[a.severity.toLowerCase()] || COLORS.muted;
      const startY = doc.y;
      doc.rect(50, startY, 4, 55).fill(sevColor);
      doc.fillColor(sevColor).fontSize(8).font('Helvetica-Bold').text(a.severity, 62, startY + 4);
      doc.fillColor('black').fontSize(11).font('Helvetica-Bold').text(a.title, 62, startY + 16, { width: pageWidth - 12 });
      doc.fillColor(COLORS.muted).fontSize(9).font('Helvetica').text(
        `${new Date(a.createdAt).toLocaleString()}  |  ${a.ipAddress || 'N/A'}  |  ${a.type}`,
        62, startY + 32
      );
      doc.y = startY + 62;
    });
  }

  doc.addPage();
  doc.fillColor('black').fontSize(16).font('Helvetica-Bold').text('Tamper and Unauthorized Attempts');
  doc.moveDown(0.5);
  doc.fillColor(COLORS.muted).fontSize(9).font('Helvetica').text(`Showing ${tamperLogs.length} events`);
  doc.moveDown(0.8);

  if (tamperLogs.length === 0) {
    doc.fillColor(COLORS.muted).fontSize(11).text('No tamper attempts recorded.');
  } else {
    tamperLogs.forEach((t) => {
      if (doc.y > doc.page.height - 80) doc.addPage();
      doc.fillColor(COLORS.critical).fontSize(9).font('Helvetica-Bold').text('ALERT: ' + t.action, 50);
      doc.fillColor('black').fontSize(10).font('Helvetica').text(`User: ${t.user?.email || 'unknown'}  |  IP: ${t.ipAddress || 'N/A'}`, 50, doc.y + 2);
      doc.fillColor(COLORS.muted).fontSize(9).text(new Date(t.createdAt).toLocaleString(), 50, doc.y + 2);
      doc.moveDown(0.6);
    });
  }

  doc.addPage();
  doc.fillColor('black').fontSize(16).font('Helvetica-Bold').text('Locked Accounts Snapshot');
  doc.moveDown(0.5);
  doc.fillColor(COLORS.muted).fontSize(9).font('Helvetica').text(`Currently ${lockedUsers.length} locked accounts`);
  doc.moveDown(0.8);

  if (lockedUsers.length === 0) {
    doc.fillColor(COLORS.muted).fontSize(11).text('No locked accounts.');
  } else {
    lockedUsers.forEach((u) => {
      if (doc.y > doc.page.height - 80) doc.addPage();
      doc.fillColor('black').fontSize(11).font('Helvetica-Bold').text(`${u.fullName} (${u.role})`, 50);
      doc.fillColor(COLORS.muted).fontSize(9).font('Helvetica').text(`${u.email}  |  ${u.failedAttempts} failed attempts`, 50, doc.y + 2);
      doc.text(`Reason: ${u.lockedReason || 'N/A'}`, 50);
      doc.text(`Locked at: ${u.lockedAt ? new Date(u.lockedAt).toLocaleString() : 'N/A'}`, 50);
      doc.moveDown(0.6);
    });
  }

  doc.fontSize(8).fillColor(COLORS.muted).text(
    'Confidential - Campus Security System - Automated Report',
    50, doc.page.height - 40, { align: 'center', width: pageWidth }
  );

  doc.end();
  return done;
}